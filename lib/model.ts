// Token Radar's value model (radar-2): one snapshot of the protocol universe in, one ranked
// board out. The board ranks only genuine launch candidates: protocols that record no token and
// are not a wrapped, staked or bridged product of a token that already trades. The watchlist is
// the floor — every one of its 40 slugs is ranked — and the early radar adds every launch
// candidate below the floor, not just the biggest ones.
//
// Implied value follows only from the snapshot's own figures:
//
//   base     = tvl_usd x BASE_MULTIPLE
//   growth   = clamp(change_7d, -80, 200) per cent
//   growth   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity = 0.5 + min(age_days, 1460) / 1460 x 0.7   (age unknown: 365 days)
//   breadth  = 1 + min(chains, 5) x 0.02
//   implied  = max(1, round(base x growth x maturity x breadth))
//
// TVL sets the scale, seven-day growth moves it most (a protocol compounding fast is worth more
// than a stagnant one the same size), age with no token adds a premium for the wait, and running
// on more chains adds a little for distribution. No protocol name is ever special-cased: the same
// function scores every row, and the dashboard recomputes each row's number in the page.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.6,
  growth_floor: -80,
  growth_cap: 200,
  maturity_floor: 0.5,
  maturity_range: 0.7,
  maturity_days: 1460,
  unknown_age_days: 365,
  breadth_per_chain: 0.02,
  breadth_max_chains: 5,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many live-token protocols the Already trading view carries, by market cap. */
export const LIVE_ROWS = 30;

